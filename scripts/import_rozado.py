"""Import Rozado's CVs and job descriptions into data/records/rozado/.

    python scripts/import_rozado.py <folder holding CVs.csv and job_descriptions.csv>

The two CSVs are the top level of "experimental data.rar" on Zenodo
(10.5281/zenodo.17173798, CC BY 4.0). They are copied verbatim to raw/, then
cleaned into cvs.jsonl and jds.jsonl by the rules in grail/probe/records_cv.py:
a CV with a fairness cue or a gendered association is excluded; a job
description loses the paragraph carrying an equal-opportunity statement and is
excluded if that leaves under 250 words. PROVENANCE.json records hashes and
every exclusion, so the cleaning is auditable and repeatable.
"""
from __future__ import annotations

import collections
import hashlib
import json
import os
import shutil
import sys
from datetime import datetime, timezone

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from config import ROOT, STIMULUS_DIR
from grail.probe.records_cv import SOURCE, import_raw
from grail.probe.templates import load_pack

OUT = os.path.join(ROOT, "data", "records", "rozado")
PACK = "employment_rozado"


def sha(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    src = sys.argv[1]
    pack = load_pack(PACK, STIMULUS_DIR)
    excluded = list(pack["source"].get("excluded_professions", {}))

    os.makedirs(os.path.join(OUT, "raw"), exist_ok=True)
    hashes = {}
    for name in ("CVs.csv", "job_descriptions.csv"):
        dst = os.path.join(OUT, "raw", name)
        shutil.copyfile(os.path.join(src, name), dst)
        hashes[name] = sha(dst)

    data = import_raw(os.path.join(OUT, "raw"), excluded)
    for name, rows in (("cvs.jsonl", data["cvs"]), ("jds.jsonl", data["jds"])):
        with open(os.path.join(OUT, name), "w", encoding="utf-8") as fh:
            for row in rows:
                fh.write(json.dumps(row, ensure_ascii=False) + "\n")

    per_prof = collections.Counter(c["profession"] for c in data["cvs"])
    log = data["log"]
    prov = {
        **SOURCE,
        "url": "https://doi.org/" + SOURCE["doi"],
        "archive_file": "experimental data.rar (top-level CVs.csv, job_descriptions.csv)",
        "imported_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "raw_sha256": hashes,
        "cleaned_sha256": {n: sha(os.path.join(OUT, n)) for n in ("cvs.jsonl", "jds.jsonl")},
        "n_raw": {"cvs": 700, "jds": 700, "professions": 70},
        "n_kept": {"cvs": len(data["cvs"]), "jds": len(data["jds"]),
                   "professions": len(per_prof)},
        "excluded_professions": pack["source"]["excluded_professions"],
        "cv_excluded_for_cue": log["cv_excluded_cue"],
        "jd_cleaned": log["jd_cleaned"],
        "jd_paragraphs_dropped": log["jd_paragraphs_dropped"],
        "jd_excluded": log["jd_excluded_short_or_cue"],
        "min_cvs_per_profession": min(per_prof.values()),
        "note": "CVs and job descriptions were generated by 13 LLMs for Rozado's "
                "study; they are synthetic documents with realistic structure, not "
                "real applicants. The CVs carry no names.",
    }
    with open(os.path.join(OUT, "PROVENANCE.json"), "w", encoding="utf-8") as fh:
        json.dump(prov, fh, indent=2, ensure_ascii=False)
    print(json.dumps({k: prov[k] for k in ("n_kept", "jd_cleaned", "jd_paragraphs_dropped",
                                           "min_cvs_per_profession")}, indent=2))
    print(f"CVs excluded for a cue: {len(log['cv_excluded_cue'])}; "
          f"job descriptions excluded: {len(log['jd_excluded_short_or_cue'])}")


if __name__ == "__main__":
    main()
